"""Basic number manipulation utilities."""
def double(n):
    """Double the value of n."""
    result = n * 2
    return result

def halve(n):
    """Return n divided by 2 using integer division."""
    result = n // 2
    return result

def increment(n):
    """Return n plus 1."""
    result = n + 1
    return result

def decrement(n):
    """Return n minus 1."""
    result = n - 1
    return result

def negate(n):
    """Return the additive inverse of n."""
    result = -n
    return result