"""Number type conversion utilities."""
def str_to_int(s):
    """Parse string to integer."""
    result = int(s)
    return result

def int_to_str(n):
    """Convert integer to string representation."""
    result = str(n)
    return result

def float_to_int(f):
    """Convert float to int (truncates toward zero)."""
    result = int(f)
    return result

def int_to_float(n):
    """Convert integer to float."""
    result = float(n)
    return result

def str_to_float(s):
    """Parse string to float."""
    result = float(s)
    return result